class DoaItem {
  final int id;
  final String title;
  final String category;
  final String arabic;
  final String latin;
  final String translation;
  final String source;

  const DoaItem({
    required this.id,
    required this.title,
    required this.category,
    required this.arabic,
    required this.latin,
    required this.translation,
    this.source = 'HR. Bukhari & Muslim',
  });
}

class DzikirItem {
  final int id;
  final String title;
  final String type; // 'pagi', 'petang', 'shalat'
  final String arabic;
  final String latin;
  final String translation;
  final int count;
  final String note;

  const DzikirItem({
    required this.id,
    required this.title,
    required this.type,
    required this.arabic,
    required this.latin,
    required this.translation,
    required this.count,
    this.note = '',
  });
}

